<?php

declare(strict_types=1);

namespace Vusys\Exocomp\Inference;

use Vusys\Exocomp\Analysis\Analyser;
use Vusys\Exocomp\Index\SymbolRecord;
use Vusys\Exocomp\Project\ClassSource;
use Vusys\Exocomp\Project\LoadedClass;
use Vusys\Exocomp\Symbol\Confidence;
use Vusys\Exocomp\Symbol\Identifier;
use Vusys\Exocomp\Symbol\SymbolKind;

/**
 * Members a class says it has: `@method`, `@property` and `@mixin`.
 *
 * This is where almost all magic actually lives. Counted over a measured Laravel application,
 * the annotations outnumbered the `__call` bodies by roughly seven thousand to one — which is
 * worth stating plainly, because the interesting problem (read the magic method and work out
 * what it forwards to) is not the one that pays.
 *
 * Everything here is {@see Confidence::Inferred} and can never be anything else. An annotation
 * is a claim about the code rather than a fact of it: nobody checks it, it goes stale silently,
 * and a great many of them are generated by a tool that read the database on some past
 * afternoon. It is worth reading and never worth rewriting on.
 *
 * `@mixin` is the interesting one. It says "my magic forwards to that class", which converts an
 * unknowable call into an ordinary member lookup on a named class — so it can name a real
 * declaration, and a rename of that declaration has to account for these call sites. The claim
 * that the forwarding happens at all is still just a claim, so the answer stays inferred.
 */
final class AnnotatedMembers implements MagicSource
{
    private const int MIXIN_DEPTH = 4;

    private readonly DocBlockTypes $docblocks;

    /** @var array<string, array{methods: array<string, array{type: ?string, tag: string}>, properties: array<string, array{type: ?string, tag: string}>, mixins: list<string>}> */
    private array $annotations = [];

    public function __construct(
        private readonly ClassSource $source,
        private readonly Members $members,
    ) {
        $this->docblocks = new DocBlockTypes;
    }

    public function method(string $ownerFqn, string $name): ?MagicMember
    {
        return $this->look($ownerFqn, $name, SymbolKind::Method, []);
    }

    public function property(string $ownerFqn, string $name): ?MagicMember
    {
        return $this->look($ownerFqn, $name, SymbolKind::Property, []);
    }

    /**
     * An annotation names the member exactly as the call site writes it, so there is nothing to
     * translate.
     *
     * @return list<string>
     */
    public function spellings(string $ownerFqn, string $declaredName): array
    {
        return [];
    }

    /**
     * @param  list<string>  $seen
     */
    private function look(string $ownerFqn, string $name, SymbolKind $kind, array $seen): ?MagicMember
    {
        if (count($seen) > self::MIXIN_DEPTH || in_array(Identifier::fold($ownerFqn), $seen, true)) {
            return null;
        }

        $seen[] = Identifier::fold($ownerFqn);
        $ancestry = $this->source->withAncestors($ownerFqn);

        foreach ($ancestry as $class) {
            $claim = $this->claim($class, $name, $kind);

            if ($claim instanceof MagicMember) {
                return $claim;
            }
        }

        // Mixins are searched only after every annotation in the ancestry has been, so that a
        // class's own account of itself wins over one it borrowed.
        foreach ($ancestry as $class) {
            foreach ($this->read($class)['mixins'] as $mixin) {
                $target = Analyser::qualify($mixin, $class->fqn, $class->analysis->imports);
                $through = $this->throughMixin($target, $name, $kind, $seen);

                if ($through instanceof MagicMember) {
                    return $through;
                }
            }
        }

        return null;
    }

    /**
     * @param  list<string>  $seen
     */
    private function throughMixin(string $target, string $name, SymbolKind $kind, array $seen): ?MagicMember
    {
        $declared = $this->members->declared($target, $name, $kind);

        if ($declared instanceof SymbolRecord) {
            return MagicMember::spelled(
                $target.'::'.$declared->name,
                $declared->typeFqn,
                Confidence::Inferred,
                sprintf('declared on %s, reached through @mixin', $target),
            );
        }

        $nested = $this->look($target, $name, $kind, $seen);

        if (! $nested instanceof MagicMember) {
            return null;
        }

        // A mixin pointing at a class that only *claims* the member yields a claim, not a
        // declaration. Passing an empty string on would have manufactured one out of nothing,
        // and everything downstream treats a declaration as somewhere it can go.
        return $nested->declaration === null
            ? MagicMember::claimed($nested->type, $nested->reason.', reached through @mixin')
            : MagicMember::spelled($nested->declaration, $nested->type, Confidence::Inferred, $nested->reason.', reached through @mixin');
    }

    private function claim(LoadedClass $class, string $name, SymbolKind $kind): ?MagicMember
    {
        $annotations = $this->read($class);
        $tags = $kind === SymbolKind::Method ? $annotations['methods'] : $annotations['properties'];

        foreach ($tags as $declared => $claim) {
            // Method names fold case in PHP and property names do not, which holds for the
            // annotated ones exactly as it does for the declared ones.
            $matches = $kind === SymbolKind::Method
                ? strcasecmp($declared, $name) === 0
                : $declared === $name;

            if (! $matches) {
                continue;
            }

            $type = $claim['type'];

            return MagicMember::claimed(
                $type === null ? null : Analyser::qualify($type, $class->fqn, $class->analysis->imports),
                sprintf('%s on %s', $claim['tag'], $class->fqn),
            );
        }

        return null;
    }

    /**
     * @return array{methods: array<string, array{type: ?string, tag: string}>, properties: array<string, array{type: ?string, tag: string}>, mixins: list<string>}
     */
    private function read(LoadedClass $class): array
    {
        $key = Identifier::fold($class->fqn);

        return $this->annotations[$key] ??= $this->docblocks->members($class->node->getDocComment()?->getText() ?? '');
    }
}
